# ====================================
# Variables Examples
# ====================================

# -----------------------------------
# Examples 1 - Store a String
# -----------------------------------

# Storing a person's name
name = "Shruti"

#printing the value
print(name)

# ------------------------------------
# Example 2 - Store a number
# -----------------------------------

# storing age
age = 24
print(age)


# -----------------------------------
# Examples 3 - Multiple Variables
# ----------------------------------
country = "USA"
salary = 5000

print(country)
print(salary)

# ------------------------------------
# Examples 4 - Calculations using variables
# ---------------------------------------

price = 25
quantity = 4

# calculate total cost
total = price* quantity

print(total)

# ------------------------------------
# Examples 5 - Update Variables Value
# -----------------------------------

score = 50
#updating value
score = score +10
print(score)

# -----------------------------------
# Examples 6 - Swap Variables
# -----------------------------------

a = 5
b = 10

# swapping Values
a, b = b, a

print(a)
print(b)

# ----------------------------------
# Examples 7 - Boolean Variable
# ----------------------------------
is_logged_in = True
print(is_logged_in)

# ----------------------------------
# Examples 8 - Backend Style Example
# ----------------------------------

user_id = 101
api_status = 200
is_admin = False

print(user_id)
print(api_status)
